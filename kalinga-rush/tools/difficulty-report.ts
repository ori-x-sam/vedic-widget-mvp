// Difficulty report (§5): a "human-ish" bot replays the frame-perfect plan with
// an 80 ms reaction delay and timing jitter, many times per record, and logs
// how often it gets hit. Writes docs/difficulty-report.md with a curve chart.
// Run: npm run difficulty   (env TRIALS=24)
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { STEP } from '../src/config';
import { OUTLINE, RECORDS } from '../src/data/records';
import { vehicle } from '../src/data/vehicles';
import { Rng } from '../src/lib/rng';
import { recordSpeed, forgiveness } from '../src/systems/difficulty';
import { buildLevel } from '../src/systems/spawner';
import { createSim, stepSim, type Level } from '../src/systems/sim';
import { DECISION_STEPS, solveLevel } from '../src/systems/solver';
import type { VehicleProfile } from '../src/systems/physics';

const LANE = 598;
const TRIALS = Number(process.env.TRIALS ?? 24);
const REACTION_S = 0.08;

/** Turn a plan into press/release times, then replay them late and jittered. */
function humanRun(level: Level, p: VehicleProfile, plan: Uint8Array, rng: Rng): { hits: number; caught: boolean } {
  const presses: { t: number; hold: number }[] = [];
  let cur: { t: number; hold: number } | null = null;
  for (let i = 0; i < plan.length; i++) {
    const t = i * DECISION_STEPS * STEP;
    if (plan[i] === 2) { cur = { t, hold: 0 }; presses.push(cur); }
    if (plan[i] !== 0 && cur) cur.hold = t + DECISION_STEPS * STEP - cur.t;
    if (plan[i] === 0) cur = null;
  }
  // A person anticipates (they can see 1 s ahead) but presses with ~80 ms of
  // reaction error either side, and holds a little imprecisely.
  const timed = presses.map((x) => ({ t: x.t + rng.range(-REACTION_S, REACTION_S), hold: Math.max(0.02, x.hold * rng.range(0.8, 1.2)) }));
  for (const e of level.entities) { e.taken = false; e.bonus = false; if (e.dolphin) { e.dolphin.startT = null; e.dolphin.bonus = false; } }
  const s = createSim(level, { lives: 99 });
  let k = 0;
  let held = false;
  let until = -1;
  while (!s.ended && !s.dead && s.t < level.seconds + 2) {
    let pressed = false;
    while (k < timed.length && timed[k].t <= s.t) { pressed = true; until = timed[k].t + timed[k].hold; k++; }
    held = s.t < until;
    stepSim(s, level, p, { pressed, held }, STEP, { lives: 99 });
    s.events.length = 0;
  }
  return { hits: s.hits, caught: s.recordCaught };
}

interface Row { id: string; num: number; act: number; speed: number; forgive: number; hazards: number; hitsPerRun: number; clean: number; caught: number }
const rows: Row[] = [];
for (const o of OUTLINE) {
  const rec = RECORDS[o.id];
  const p = vehicle(rec.ride);
  const speed = recordSpeed(rec.num);
  const level = buildLevel(rec, { seed: 1, speed, laneY: LANE, profile: p });
  const res = solveLevel(level, p);
  const rng = new Rng(`human:${o.id}`);
  let hits = 0, clean = 0, caught = 0;
  if (res.ok) {
    for (let i = 0; i < TRIALS; i++) {
      const r = humanRun(level, p, res.plan, rng);
      hits += r.hits;
      if (r.hits === 0) clean++;
      if (r.caught) caught++;
    }
  }
  const row = { id: o.id, num: o.num, act: o.act, speed, forgive: forgiveness(rec.num), hazards: level.entities.filter((e) => e.kind === 'hazard').length, hitsPerRun: hits / TRIALS, clean: clean / TRIALS, caught: caught / TRIALS };
  rows.push(row);
  console.log(`${String(o.num).padStart(2)} ${o.id.padEnd(3)} speed ${speed.toFixed(0).padStart(4)} px/s · hitbox ×${row.forgive.toFixed(2)} · ${String(row.hazards).padStart(3)} hazards · ${row.hitsPerRun.toFixed(2)} hits/run · ${(row.clean * 100).toFixed(0)}% clean`);
}

const max = Math.max(...rows.map((r) => r.hitsPerRun), 0.1);
const bar = (v: number) => '█'.repeat(Math.round((v / max) * 30)).padEnd(30, '·');
const md = [
  '# Difficulty report',
  '',
  `Generated by \`tools/difficulty-report.ts\`. A "human-ish" bot replays the frame-perfect solution of each record (seed 1, normal speed) with ±${REACTION_S * 1000} ms timing error and ±20% hold error, ${TRIALS} times. **Hits/run** is how often it loses a diya; **clean** is the share of runs with no hit. Hitboxes start generous (×0.62) and tighten to ×1.0 by Record 37.`,
  '',
  '```',
  ...rows.map((r) => `${String(r.num).padStart(2)} ${r.id.padEnd(3)} ${bar(r.hitsPerRun)} ${r.hitsPerRun.toFixed(2)}`),
  '```',
  '',
  '| # | Record | Act | Speed (px/s) | Hitbox scale | Hazards | Hits / run | Clean runs | Record caught |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.num} | ${r.id} | ${r.act} | ${r.speed.toFixed(0)} | ${r.forgive.toFixed(2)} | ${r.hazards} | ${r.hitsPerRun.toFixed(2)} | ${(r.clean * 100).toFixed(0)}% | ${(r.caught * 100).toFixed(0)}% |`),
  '',
];
mkdirSync(join(import.meta.dirname, '..', 'docs'), { recursive: true });
writeFileSync(join(import.meta.dirname, '..', 'docs', 'difficulty-report.md'), md.join('\n'));
console.log('wrote docs/difficulty-report.md');
